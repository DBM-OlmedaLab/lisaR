  empty_info <- lisaR:::lisa_report_package_write_xlsx(data.frame(table_id = "T0002", role = "empty"), td, tempfile(fileext = ".xlsx"))
  expect_equal(empty_info$included, 0L)
  expect_equal(empty_info$csv_only, 1L)
})

test_that("report packaging annotated profile is effective all-true and auditable", {
  fx <- file.path(tempdir(), "report_package_fixture-annotated"); unlink(fx, recursive = TRUE)
  dir.create(file.path(fx, "d"), recursive = TRUE); dir.create(file.path(fx, "g")); dir.create(file.path(fx, "m"))
  write.table(data.frame(symbol = "STAT3"), file.path(fx, "d", "T0001.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)
  writeLines("<svg xmlns=\"http://www.w3.org/2000/svg\"><rect width=\"5\" height=\"5\"/></svg>", file.path(fx, "g", "F0001.svg"))
  reg <- data.frame(table_id = c("T0001", "F0001"), path = c("d/T0001.tsv", "g/F0001.svg"), artifact_type = c("table", "figure"), role = c("single_de/category_gene_evidence", "single_de/gene_cards/example.svg"), analysis_id = "A", contrast_id = "", collection = "PATHWAYS", sha256 = vapply(file.path(fx, c("d/T0001.tsv", "g/F0001.svg")), lisaR:::lisa_report_package_sha256, character(1)), stringsAsFactors = FALSE)
  write.table(reg, file.path(fx, "m", "registry.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)
  write.table(data.frame(analysis_id = "A", label = "Mouse protein"), file.path(fx, "m", "de.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)
  write.table(data.frame(contrast_id = character()), file.path(fx, "m", "cx.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)
  write.table(data.frame(analysis_collection = "PATHWAYS"), file.path(fx, "m", "col.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)
  write.table(data.frame(table_id = reg$table_id, source_path = c("x.tsv", "x.svg"), artifact_type = reg$artifact_type, source_sha256 = reg$sha256), file.path(fx, "m", "prov.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)
  files <- sort(list.files(fx, recursive = TRUE, full.names = FALSE)); write.table(data.frame(path = files, sha256 = vapply(file.path(fx, files), lisaR:::lisa_report_package_sha256, character(1))), file.path(fx, "m", "sha256.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)

  minimal <- tempfile("w8-min-"); annotated <- tempfile("w8-all-")
  build_lisa_report_package(fx, minimal, "minimal")
  result <- build_lisa_report_package(fx, annotated, "annotated")
  expect_false(file.exists(file.path(minimal, "g", "F0001.svg")))
  expect_true(file.exists(file.path(annotated, "g", "F0001.svg")))
  expect_equal(result$figures, 1L)
  options <- read_lisa_tsv(file.path(annotated, "m", "options.tsv"))
  expect_true(all(as.logical(options$value)))
  qc <- read_lisa_tsv(file.path(annotated, "m", "qc.tsv"))
  expect_equal(qc$state[qc$product == "gene_cards"], "PASS")
  expect_equal(qc$state[qc$product == "kegg_maps"], "not_available")
  expect_true(lisaR:::lisa_report_foundation_verify_links(annotated))
})
