  expect_identical(lisaR:::lisa_report_package_visual_product("results/leading_edge_ge_ab12/plot.png"), "heatmaps")
  td <- tempfile("w8xlsx-"); dir.create(td)
  write.table(data.frame(value = c(NA_character_, "ok")), file.path(td, "T0001.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)
  reg <- data.frame(table_id = "T0001", role = "test", stringsAsFactors = FALSE)
  out <- tempfile(fileext = ".xlsx")
  info <- lisaR:::lisa_report_package_write_xlsx(reg, td, out)
  expect_true(file.exists(out))
  expect_equal(info$included, 1L)
  expect_equal(info$csv_only, 0L)

