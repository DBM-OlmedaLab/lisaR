test_that("report packaging bundle is registry-driven, checksummed, and offline", {
  fx <- file.path(tempdir(), "report_package_fixture"); unlink(fx, recursive = TRUE)
  dir.create(file.path(fx, "d"), recursive = TRUE); dir.create(file.path(fx, "m"))
  tab <- data.frame(category_id = c("P01", "P02"), symbol = c("SGS", "STAT3"), mean_NES = c(1.2, -0.4), stringsAsFactors = FALSE)
  write.table(tab, file.path(fx, "d", "T0001.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)
  reg <- data.frame(table_id = "T0001", path = "d/T0001.tsv", role = "single_de/category_gene_evidence", analysis_id = "A", contrast_id = NA_character_, collection = "PATHWAYS", sha256 = lisaR:::lisa_report_package_sha256(file.path(fx, "d", "T0001.tsv")))
  write.table(reg, file.path(fx, "m", "registry.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)
  write.table(data.frame(analysis_id = "A", label = "Transcriptomic SGS"), file.path(fx, "m", "de.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)
  write.table(data.frame(contrast_id = "C", contrast_label = "A versus B"), file.path(fx, "m", "cx.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)
  write.table(data.frame(analysis_collection = "PATHWAYS"), file.path(fx, "m", "col.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)
  write.table(data.frame(source_path = "archived/output.tsv", role = "canonical", source_sha256 = reg$sha256), file.path(fx, "m", "prov.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)
  files <- sort(list.files(fx, recursive = TRUE, full.names = FALSE)); write.table(data.frame(path = files, sha256 = vapply(file.path(fx, files), lisaR:::lisa_report_package_sha256, character(1))), file.path(fx, "m", "sha256.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)
  out_parent <- tempfile("report_package_output-")
  dir.create(out_parent)
  out <- file.path(out_parent, ".", "bundle")
  result <- build_lisa_report_package(fx, out)
  expect_identical(
    dirname(result$index), normalizePath(out, winslash = "/", mustWork = TRUE)
  )
  expect_true(file.exists(result$index)); expect_true(file.exists(file.path(out, "d", "report.xlsx"))); expect_true(file.exists(file.path(out, "d", "tables.zip")))
  expect_identical(readBin(file.path(out, "d", "T0001.csv"), "raw", n = 3L), as.raw(c(0xef, 0xbb, 0xbf)))
  expect_equal(read.csv(file.path(out, "d", "T0001.csv"), fileEncoding = "UTF-8-BOM", check.names = FALSE)$symbol, tab$symbol)
  long_root <- file.path(tempdir(), paste(rep("windows-safe-root", 10L), collapse = "-")); unlink(long_root, recursive = TRUE); dir.create(long_root, recursive = TRUE)
  utils::unzip(file.path(out, "d", "tables.zip"), exdir = long_root)
  expect_true(file.exists(file.path(long_root, "T0001.csv")))
  expect_true(lisaR:::lisa_report_foundation_verify_links(out)); expect_lte(result$max_path, 120L); expect_lte(result$max_html, 1024^2)
  m <- read_lisa_tsv(file.path(out, "m", "manifest.tsv")); expect_true(all(vapply(seq_len(nrow(m)), function(i) identical(lisaR:::lisa_report_package_sha256(file.path(out, m$path[[i]])), m$sha256[[i]]), logical(1))))
  expect_equal(openxlsx::sheets(openxlsx::loadWorkbook(file.path(out, "d", "report.xlsx")))[1], "README")
  malformed <- read_lisa_tsv(file.path(fx, "m", "sha256.tsv"))
  malformed$sha256[[1]] <- ""
  write.table(malformed, file.path(fx, "m", "sha256.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)
  expect_error(lisaR:::lisa_report_package_read_fixture(fx), "manifest is malformed")
})

